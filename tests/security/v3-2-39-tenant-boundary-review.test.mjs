import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../../',import.meta.url));
const read=p=>readFileSync(resolve(root,p),'utf8');
const m=JSON.parse(read('spec/v3-2-39-tenant-boundary-review.json'));
test('V3.2-39 refuses all production execution and release authority',()=>{
 assert.equal(m.schema_version,'v3.2-39-tenant-boundary-review-v1');
 assert.equal(m.parent_pr,45);
 assert.equal(m.proof_level,'STATIC_SOURCE_REVIEW_ONLY');
 for(const k of ['dynamic_security_uat_completed','production_integration_allowed','execution_allowed','release_allowed','merge_authorized','deploy_authorized','new_migration'])assert.equal(m[k],false,k);
 assert.equal(m.hold_active_required,true);
 assert.equal(m.student_primary,true);
 assert.equal(m.family_optional,true);
 assert.equal(m.real_uat,'NOT_RUN');
 assert.equal(m.external_approvals,'MISSING');
 const doc=read('docs/V3.2-39_TENANT_PERMISSIONS_SECURITY_REVIEW.md');
 for(const term of ['hold_active','不合并','不部署','proposed-unimplemented','SECURITY DEFINER'])assert.ok(doc.includes(term),term);
});
test('V3.2-39 audits real source SQL permission clauses, without granting production access',()=>{
 const hard=read('db/migrations/034_preintegration_authority_hard_gates.sql');
 const report=read('db/migrations/035_readonly_integration_uat_report.sql');
 const preview=read('db/migrations/036_scoped_uat_preview_reader.sql');
 assert.deepEqual(m.source_migrations,['034_preintegration_authority_hard_gates.sql','035_readonly_integration_uat_report.sql','036_scoped_uat_preview_reader.sql']);
 assert.match(hard,/CHECK\(NOT production_verified\)/);
 assert.match(hard,/ms\.access_actor\(\)/);
 assert.match(hard,/WHERE id=p_request AND organization_id=org/);
 assert.match(hard,/REVOKE ALL ON FUNCTION ms\.readonly_integration_hard_gate/);
 assert.match(report,/ms\.readonly_integration_hard_gate\(p_request\)/);
 assert.match(report,/GRANT EXECUTE ON FUNCTION ms\.readonly_integration_uat_report/);
 assert.match(preview,/CREATE ROLE ms_uat_preview_reader NOLOGIN/);
 assert.match(preview,/security_barrier=true/);
 assert.match(preview,/REVOKE ALL ON ms\.scoped_uat_preview_choices FROM PUBLIC/);
 assert.equal(JSON.parse(read('api/openapi/crm-integration.v1.json'))['x-contract-status'],m.contracts);
 assert.equal(JSON.parse(read('api/openapi/market-sales.v1.json'))['x-contract-status'],m.contracts);
 const names=readdirSync(resolve(root,'db/migrations')).filter(n=>/^\d{3}_.+\.sql$/.test(n)).sort();
 assert.equal(names.length,38);
 assert.equal(names[names.length-1].slice(0,3),'038');
});
